"""Synthetic multi-venue L2 dataset: generation, immutable storage, loading.

Datasets are written once to ``<root>/<name>-<hash>/`` with a manifest that
records the generating config, a SHA-256 of the array file and the
chronological train/validation/test step ranges. Existing datasets are never
overwritten; a changed config yields a new directory.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from scipy.signal import lfilter

from ..config import base_dir, config_hash, venues
from ..core import ASK, BID, MS

GENERATOR_VERSION = "1"
LICENSE = "Synthetic data generated by this repository; no third-party market data. CC0."


def generate_arrays(cfg: dict) -> dict:
    d = cfg["data"]
    vcfgs = venues(cfg)
    T, L, V = int(d["steps"]), int(d["levels"]), len(vcfgs)
    dt_s = d["dt_ms"] / 1000.0
    rng = np.random.default_rng(int(d["seed"]))
    start = int(round(cfg["instrument"]["start_price"] / cfg["instrument"]["tick_size"]))

    moves = rng.random(T) < d["mid_move_prob"]
    dirs = rng.integers(0, 2, T) * 2 - 1
    mid = start + np.cumsum(moves * dirs)

    # Sticky one-tick widening per venue and side (two-state Markov chain).
    u = rng.random((T, V, 2))
    widen = np.zeros((T, V, 2), dtype=np.int32)
    on = np.array([v.widen_on_prob for v in vcfgs])[:, None]
    off = np.array([v.widen_off_prob for v in vcfgs])[:, None]
    state = np.zeros((V, 2), dtype=bool)
    for t in range(T):
        state = np.where(state, u[t] >= off, u[t] < on)
        widen[t] = state

    hs = np.array([v.half_spread_ticks for v in vcfgs], dtype=np.int32)
    lv = np.arange(L, dtype=np.int32)
    px = np.zeros((2, T, V, L), dtype=np.int32)
    px[BID] = (mid[:, None] - hs[None, :] - widen[:, :, BID])[:, :, None] - lv
    px[ASK] = (mid[:, None] + hs[None, :] + widen[:, :, ASK])[:, :, None] + lv

    # Displayed sizes: log-AR(1) around a venue depth profile.
    a, sig = d["size_ar"], d["size_sigma"]
    eps = rng.standard_normal((T, 2, V, L))
    eps[0] /= np.sqrt(1 - a * a)
    z = lfilter([np.sqrt(1 - a * a)], [1.0, -a], eps, axis=0)
    depth = np.array([v.depth_lots for v in vcfgs])[:, None] * d["depth_decay"] ** lv[None, :]
    sz = np.rint(depth[None, None] * np.exp(sig * z - 0.5 * sig * sig)).astype(np.int32)
    sz = np.transpose(sz, (1, 0, 2, 3))  # -> [side, T, V, L]

    status = np.zeros((T, V), dtype=np.uint8)
    for i, v in enumerate(vcfgs):
        p = v.outage_rate_per_min / 60.0 * dt_s
        if p > 0:
            n = max(1, int(round(v.outage_ms / d["dt_ms"])))
            for s in np.flatnonzero(rng.random(T) < p):
                status[s:s + n, i] = 1

    rate = np.array([v.flow_rate for v in vcfgs]) * dt_s
    flow = rng.poisson(rate[None, :, None], size=(T, V, 2)).astype(np.int32)

    return {"mid": mid.astype(np.int32), "px": px, "sz": sz, "status": status, "flow": flow}


def _splits(cfg: dict) -> dict:
    T = int(cfg["data"]["steps"])
    out, start = {}, 0
    names = ["train", "validation", "test"]
    for i, name in enumerate(names):
        end = T if i == len(names) - 1 else start + int(round(cfg["data"]["splits"][name] * T))
        out[name] = [start, end]
        start = end
    return out


def dataset_dir(cfg: dict) -> Path:
    h = config_hash(cfg, ["instrument", "data", "venues"])
    return base_dir(cfg) / cfg["data"]["root"] / f"{cfg['name']}-{h}"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepare(cfg: dict) -> Path:
    """Generate the dataset for `cfg` unless an identical one already exists."""
    out = dataset_dir(cfg)
    if (out / "manifest.json").exists():
        Dataset(out)  # verifies checksum
        return out
    out.mkdir(parents=True, exist_ok=True)
    arrays = generate_arrays(cfg)
    np.savez_compressed(out / "book.npz", **arrays)
    manifest = {
        "name": cfg["name"],
        "generator_version": GENERATOR_VERSION,
        "license": LICENSE,
        "timestamps": "integer nanoseconds from window start; one snapshot per dt_ms on a "
                      "single simulated clock shared by all venues",
        "sha256": _sha256(out / "book.npz"),
        "steps": int(cfg["data"]["steps"]),
        "dt_ms": cfg["data"]["dt_ms"],
        "splits": _splits(cfg),
        "config": {k: cfg[k] for k in ("instrument", "data", "venues")},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return out


class Dataset:
    def __init__(self, path, verify: bool = True):
        self.path = Path(path)
        self.manifest = json.loads((self.path / "manifest.json").read_text())
        if verify and _sha256(self.path / "book.npz") != self.manifest["sha256"]:
            raise ValueError(f"dataset checksum mismatch in {self.path}")
        with np.load(self.path / "book.npz") as z:
            arrays = {k: z[k] for k in z.files}
        self._bind(arrays, self.manifest["dt_ms"], self.manifest["splits"])

    @classmethod
    def from_arrays(cls, arrays: dict, dt_ms: float, splits: dict) -> "Dataset":
        self = cls.__new__(cls)
        self.path, self.manifest = None, {"sha256": "in-memory"}
        self._bind(arrays, dt_ms, splits)
        return self

    def _bind(self, arrays, dt_ms, splits):
        self.mid, self.px, self.sz = arrays["mid"], arrays["px"], arrays["sz"]
        self.status, self.flow = arrays["status"], arrays["flow"]
        self.T, self.V = self.status.shape
        self.L = self.px.shape[-1]
        self.dt_ns = int(round(dt_ms * MS))
        self.splits = {k: tuple(v) for k, v in splits.items()}

    def step(self, t_ns: int) -> int:
        k = t_ns // self.dt_ns
        return 0 if k < 0 else (self.T - 1 if k >= self.T else int(k))

    def mid_ticks(self, t_ns: int) -> float:
        """Exogenous consolidated mid (best bid/ask across venues that are up)."""
        k = self.step(t_ns)
        up = self.status[k] == 0
        if not up.any():
            up = np.ones(self.V, dtype=bool)
        return 0.5 * (float(self.px[BID][k, up, 0].max()) + float(self.px[ASK][k, up, 0].min()))


def load_for(cfg: dict) -> Dataset:
    path = dataset_dir(cfg)
    if not (path / "manifest.json").exists():
        raise FileNotFoundError(
            f"dataset {path} not found; run: python -m project.prepare_data --config {cfg.get('_path', '<config>')}")
    return Dataset(path)
