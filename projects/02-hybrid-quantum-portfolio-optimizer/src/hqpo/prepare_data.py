"""CLI: build the versioned price dataset named in the config.

    python -m hqpo.prepare_data --config configs/demo.yaml
"""
from __future__ import annotations

import argparse

import pandas as pd

from .config import load_config, resolve
from .data.prices import normalize_prices, save_dataset
from .data.synthetic import generate_price_panel


def prepare(cfg: dict) -> dict:
    data = cfg["data"]
    out = resolve(cfg, data["path"])
    source = data.get("source", "synthetic")
    if source == "synthetic":
        params = data["synthetic"]
        prices, sectors = generate_price_panel(**params)
        meta = {"source": "synthetic", "generator": "hqpo.data.synthetic.generate_price_panel",
                "params": params,
                "license": "Synthetic data generated by this repository; no third-party rights."}
    elif source == "csv":
        raw = pd.read_csv(resolve(cfg, data["raw_path"]), index_col=0)
        prices = raw
        sectors = data.get("sectors", {})
        meta = {"source": "csv", "raw_path": data["raw_path"],
                "license": data.get("license", "UNSPECIFIED - verify redistribution rights")}
    elif source == "yfinance":
        try:
            import yfinance as yf
        except ImportError as exc:
            raise SystemExit("data.source=yfinance needs `pip install hqpo[yfinance]`") from exc
        tickers = data["tickers"]
        raw = yf.download(tickers, start=data["start"], end=data["end"], auto_adjust=True,
                          progress=False)["Close"]
        prices = raw[tickers]
        sectors = data.get("sectors", {})
        meta = {"source": "yfinance", "tickers": tickers, "start": data["start"], "end": data["end"],
                "price_field": "auto-adjusted close",
                "license": "Yahoo Finance data: personal/research use only, not redistributable. "
                           "Do not commit the downloaded file."}
    else:
        raise SystemExit(f"unknown data.source {source!r}")
    if data.get("universe"):
        prices = prices[data["universe"]]
    prices = normalize_prices(prices)
    return save_dataset(prices, sectors, out, meta)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", required=True)
    args = ap.parse_args(argv)
    cfg = load_config(args.config)
    m = prepare(cfg)
    print(f"wrote {resolve(cfg, cfg['data']['path'])}: {m['rows']} rows x {len(m['assets'])} assets "
          f"[{m['first_date']} .. {m['last_date']}] sha256={m['sha256'][:12]}")


if __name__ == "__main__":
    main()
