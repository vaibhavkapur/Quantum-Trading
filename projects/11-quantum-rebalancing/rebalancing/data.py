"""Seeded, immutable synthetic snapshots. No network or market-data license needed."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import numpy as np
import yaml

from .model import Portfolio, canonical, digest, integer


def generate(seed: int = 7, assets: int = 3, max_trade_lots: int = 1) -> Portfolio:
    integer("seed", seed)
    integer("assets", assets, 1)
    if assets > 32:
        raise ValueError("at most 32 synthetic assets")
    rng = np.random.default_rng(seed)
    rows = []
    # Use exact decimal target fractions to avoid a floating-point sum > 1.
    units = rng.multinomial(8500, np.full(assets, 1 / assets))
    for i in range(assets):
        price = int(rng.integers(10, 61)) * 100
        shares = int(rng.integers(2, 5)) * 2
        rows.append({"symbol": f"SYN{i + 1:02d}", "price_cents": price, "current_shares": shares,
                     "lot_size": 2, "target_weight": int(units[i]) / 10000,
                     "max_trade_lots": max_trade_lots, "max_weight": 1.0, "group": "equity" if i % 2 == 0 else "bond",
                     "fee_bps": 8, "fixed_fee_cents": 15, "min_trade_notional_cents": price,
                     "max_trade_notional_cents": price * 2 * max_trade_lots,
                     "tax_rate_bps": 1500 if i == 0 else 0,
                     "tax_lots": [{"shares": shares, "basis_cents": price - 100}] if i == 0 else []})
    invested = sum(a["price_cents"] * a["current_shares"] for a in rows)
    return Portfolio.from_dict({"assets": rows, "cash_cents": invested // 2, "cash_reserve_weight": 0.05,
                                "group_caps": {"equity": 0.85}, "turnover_weight": 0.01, "cost_weight": 1.0})


def load_config(path: str | Path) -> dict:
    path = Path(path).resolve()
    config = yaml.safe_load(path.read_text())
    if not isinstance(config, dict):
        raise ValueError("config must be an object")
    allowed = {"schema_version", "dataset", "runs", "generator", "budget", "benchmark"}
    if set(config) - allowed or config.get("schema_version") != 1:
        raise ValueError("unknown config keys or unsupported schema_version")
    # Paths are relative to the config file, not the caller's working directory.
    for key in ("dataset", "runs"):
        if not isinstance(config.get(key), str):
            raise ValueError(f"config requires a {key} path")
        config[key] = str((path.parent / config[key]).resolve())
    return config


def prepare(config: dict) -> dict:
    portfolio = generate(**config.get("generator", {}))
    path = Path(config["dataset"])
    path.parent.mkdir(parents=True, exist_ok=True)
    text = canonical(portfolio.to_dict()) + "\n"
    manifest = {"schema_version": 1, "dataset_version": "synthetic-rebalancing-v1",
                "generator": config.get("generator", {}), "content_sha256": hashlib.sha256(text.encode()).hexdigest(),
                "portfolio_hash": digest(portfolio.to_dict()), "license": "CC0-1.0 (synthetic data generated by this project)",
                "timestamp_normalization": "ISO-8601 UTC; fixed snapshot, no time-series splits",
                "contains_market_data": False}
    for target, contents in [(path, text), (path.with_suffix(".manifest.json"), canonical(manifest) + "\n")]:
        if target.exists():
            if target.read_text() != contents:
                raise ValueError(f"refusing to overwrite immutable dataset or manifest: {target}")
        else:
            with target.open("x") as stream:
                stream.write(contents)
    return manifest


def load_portfolio(path: str | Path, *, verify_manifest: bool = True) -> Portfolio:
    path = Path(path)
    contents = path.read_bytes()
    if verify_manifest:
        manifest = json.loads(path.with_suffix(".manifest.json").read_text())
        if hashlib.sha256(contents).hexdigest() != manifest["content_sha256"]:
            raise ValueError("dataset SHA-256 does not match its manifest")
    return Portfolio.from_dict(json.loads(contents))

